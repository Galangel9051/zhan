// Package proxy manages only Zhan's dedicated nginx container.
package proxy

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"net"
	"net/mail"
	"net/url"
	"regexp"
	"strconv"
	"strings"
)

type Settings struct {
	Bind       string `json:"bind"`
	HTTPPort   int    `json:"http_port"`
	HTTPSPort  int    `json:"https_port"`
	DuckDomain string `json:"duck_domain"`
	DuckIP     string `json:"duck_ip"`
	DuckToken  string `json:"duck_token,omitempty"`
	TokenSet   bool   `json:"token_set"`
	Email      string `json:"email"`
	AgreeTerms bool   `json:"agree_terms"`
	Staging    bool   `json:"staging"`
	DDNS       bool   `json:"ddns"`
}
type Host struct {
	ID          string `json:"id"`
	Name        string `json:"name"`
	Domain      string `json:"domain"`
	Upstream    string `json:"upstream"`
	Enabled     bool   `json:"enabled"`
	HTTPS       bool   `json:"https"`
	Redirect    bool   `json:"redirect"`
	Websocket   bool   `json:"websocket"`
	CertExpires string `json:"cert_expires,omitempty"`
	CertError   string `json:"cert_error,omitempty"`
}
type Config struct {
	Settings Settings `json:"settings"`
	Hosts    []Host   `json:"hosts"`
	Revision int64    `json:"revision"`
}

var domainPattern = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$`)
var idPattern = regexp.MustCompile(`^[a-f0-9]{16}$`)

func Defaults() Config {
	return Config{Settings: Settings{Bind: "0.0.0.0", HTTPPort: 80, HTTPSPort: 443}, Hosts: []Host{}}
}
func Normalize(c *Config) error {
	s := &c.Settings
	if net.ParseIP(s.Bind) == nil {
		return fmt.Errorf("监听地址必须是 IP，例如 127.0.0.1 或 0.0.0.0")
	}
	if s.HTTPPort < 1 || s.HTTPPort > 65535 || s.HTTPSPort < 1 || s.HTTPSPort > 65535 || s.HTTPPort == s.HTTPSPort {
		return fmt.Errorf("HTTP / HTTPS 端口应为不同的 1–65535 整数")
	}
	s.DuckDomain = strings.ToLower(strings.TrimSpace(s.DuckDomain))
	if s.DuckDomain != "" && (!domainPattern.MatchString(s.DuckDomain) || !strings.HasSuffix(s.DuckDomain, ".duckdns.org") || strings.Count(s.DuckDomain, ".") != 2) {
		return fmt.Errorf("DuckDNS 主域名应为已注册的 name.duckdns.org")
	}
	if s.DuckIP != "" && net.ParseIP(s.DuckIP) == nil {
		return fmt.Errorf("DuckDNS IP 必须为 IPv4 或 IPv6；留空自动检测公网 IPv4")
	}
	if s.DDNS && s.DuckDomain == "" {
		return fmt.Errorf("请先填写 DuckDNS 主域名")
	}
	if s.Email != "" {
		a, e := mail.ParseAddress(s.Email)
		if e != nil || a.Address != s.Email {
			return fmt.Errorf("证书联系邮箱格式不正确")
		}
	}
	if len(c.Hosts) > 100 {
		return fmt.Errorf("最多管理 100 个代理规则")
	}
	seen := map[string]bool{}
	ids := map[string]bool{}
	for i := range c.Hosts {
		h := &c.Hosts[i]
		h.Name = strings.TrimSpace(h.Name)
		h.Domain = strings.ToLower(strings.TrimSpace(h.Domain))
		h.Upstream = strings.TrimSpace(h.Upstream)
		h.CertExpires = ""
		h.CertError = ""
		if !idPattern.MatchString(h.ID) || ids[h.ID] {
			return fmt.Errorf("代理规则 ID 无效或重复")
		}
		ids[h.ID] = true
		if len(h.Name) > 100 {
			return fmt.Errorf("规则名称不能超过 100 字节")
		}
		if !domainPattern.MatchString(h.Domain) || len(h.Domain) > 253 || seen[h.Domain] {
			return fmt.Errorf("域名 %q 无效或重复；请填写完整域名，不包含协议或端口", h.Domain)
		}
		seen[h.Domain] = true
		u, e := url.Parse(h.Upstream)
		if e != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Hostname() == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" || (u.Path != "" && u.Path != "/") || strings.ContainsAny(h.Upstream, "\r\n\t ;{}\\\"$#") {
			return fmt.Errorf("%s：上游应为 http(s)://主机:端口，不包含路径或账号", h.Domain)
		}
		hostname := u.Hostname()
		if net.ParseIP(hostname) == nil && hostname != "localhost" && !domainPattern.MatchString(hostname) {
			return fmt.Errorf("%s：上游主机格式不正确", h.Domain)
		}
		if p := u.Port(); p != "" {
			n, e := strconv.Atoi(p)
			if e != nil || n < 1 || n > 65535 {
				return fmt.Errorf("%s：上游端口无效", h.Domain)
			}
		}
		if hostname == "localhost" || hostname == "127.0.0.1" || hostname == "::1" {
			return fmt.Errorf("上游的本机地址请使用 host.docker.internal，Nginx 在独立容器中运行")
		}
		h.Upstream = strings.TrimSuffix(h.Upstream, "/")
	}
	return nil
}
func certName(h Host, s Settings) string {
	sum := sha256.Sum256([]byte(fmt.Sprintf("%t:%s", s.Staging, h.Domain)))
	return hex.EncodeToString(sum[:12])
}
func fingerprint(c Config) string {
	// Compare only the desired deployed gateway; DNS credentials do not require restart.
	hosts := append([]Host{}, c.Hosts...)
	for i := range hosts {
		hosts[i].CertExpires = ""
		hosts[i].CertError = ""
	}
	payload, _ := json.Marshal(struct {
		Bind        string
		HTTP, HTTPS int
		Staging     bool
		Hosts       []Host
	}{c.Settings.Bind, c.Settings.HTTPPort, c.Settings.HTTPSPort, c.Settings.Staging, hosts})
	return fmt.Sprintf("%x", sha256.Sum256(payload))
}
func Render(c Config) string {
	var b strings.Builder
	b.WriteString("# Generated by Zhan. Edit rules in the web interface.\nworker_processes auto;\npid /tmp/nginx.pid;\nerror_log /dev/stderr warn;\nevents { worker_connections 1024; }\nhttp {\n  include /etc/nginx/mime.types;\n  access_log /dev/stdout;\n  server_tokens off;\n  map $http_upgrade $connection_upgrade { default upgrade; '' close; }\n  server { listen 80 default_server; server_name _; return 404; }\n")
	for _, h := range c.Hosts {
		if !h.Enabled {
			continue
		}
		fmt.Fprintf(&b, "  # %s\n  server {\n    listen 80;\n    server_name %s;\n", h.ID, h.Domain)
		if h.HTTPS && h.Redirect {
			port := ""
			if c.Settings.HTTPSPort != 443 {
				port = ":" + strconv.Itoa(c.Settings.HTTPSPort)
			}
			fmt.Fprintf(&b, "    return 308 https://%s%s$request_uri;\n  }\n", h.Domain, port)
		} else {
			location(&b, h)
			b.WriteString("  }\n")
		}
		if h.HTTPS {
			fmt.Fprintf(&b, "  server {\n    listen 443 ssl;\n    server_name %s;\n    ssl_certificate /etc/nginx/certs/%s/fullchain.pem;\n    ssl_certificate_key /etc/nginx/certs/%s/privkey.pem;\n    ssl_protocols TLSv1.2 TLSv1.3;\n    ssl_session_cache shared:SSL:10m;\n", h.Domain, certName(h, c.Settings), certName(h, c.Settings))
			location(&b, h)
			b.WriteString("  }\n")
		}
	}
	b.WriteString("}\n")
	return b.String()
}
func location(b *strings.Builder, h Host) {
	fmt.Fprintf(b, "    location / {\n      proxy_pass %s;\n      proxy_http_version 1.1;\n      proxy_set_header Host $host;\n      proxy_set_header X-Real-IP $remote_addr;\n      proxy_set_header X-Forwarded-For $remote_addr;\n      proxy_set_header X-Forwarded-Proto $scheme;\n      proxy_read_timeout 60s;\n      client_max_body_size 64m;\n", h.Upstream)
	if strings.HasPrefix(h.Upstream, "https://") {
		b.WriteString("      proxy_ssl_server_name on;\n      proxy_ssl_verify on;\n      proxy_ssl_trusted_certificate /etc/ssl/certs/ca-certificates.crt;\n")
	}
	if h.Websocket {
		b.WriteString("      proxy_set_header Upgrade $http_upgrade;\n      proxy_set_header Connection $connection_upgrade;\n")
	} else {
		b.WriteString("      proxy_set_header Connection \"\";\n")
	}
	b.WriteString("    }\n")
}
